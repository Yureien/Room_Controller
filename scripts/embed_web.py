"""Embed the local page in a deterministic PROGMEM header (Python stdlib only)."""
from pathlib import Path
import argparse
import hashlib


def embed_web(source: Path, output: Path) -> None:
    page = (source / "index.html").read_text(encoding="utf-8")
    for marker, filename, tag in [
        ("<!-- CONTROLLER_CSS -->", "style.css", "style"),
        ("<!-- CONTROLLER_JS -->", "controller.js", "script"),
    ]:
        if page.count(marker) != 1:
            raise ValueError(f"index.html must contain exactly one {marker}")
        content = (source / filename).read_text(encoding="utf-8")
        if f"</{tag}" in content.lower():
            raise ValueError(f"{filename} contains an embedded closing {tag} tag")
        page = page.replace(marker, f"<{tag}>\n{content}</{tag}>")
    # C++ raw delimiters have a 16-character maximum. Content-derived suffix
    # plus explicit collision validation keeps asset edits safe and reproducible.
    delimiter = "RC" + hashlib.sha256(page.encode("utf-8")).hexdigest()[:12]
    if f'){delimiter}"' in page:
        raise ValueError("raw-string delimiter collision")
    header = (
        "// Generated by scripts/embed_web.py; edit web/ assets instead.\n"
        "#pragma once\n#include <Arduino.h>\n"
        f'const char kControlPage[] PROGMEM = R"{delimiter}({page}){delimiter}";\n'
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != header:
        output.write_text(header, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("web"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    embed_web(args.source, args.output)
